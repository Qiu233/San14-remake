using System.Text.Json.Nodes;

namespace San14.Core;

internal static class LegacySimulationParameterSaveMigration
{
    public static void Apply(JsonObject state)
    {
        if (state["NativeArmySimulation"]?["Parameters"] is not JsonObject parameters) return;
        foreach (string bankName in new[] { "Int32Values", "Float32Values" })
        {
            if (parameters[bankName] is not JsonObject bank) continue;
            foreach (string oldKey in bank.Select(pair => pair.Key).ToArray())
            {
                string? semanticKey;
                const string areaPrefix = "ce-area-statistics-current:area:";
                const string areaSuffix = ":runtime-33E590";
                if (oldKey.StartsWith(areaPrefix, StringComparison.Ordinal) && oldKey.EndsWith(areaSuffix, StringComparison.Ordinal))
                {
                    int slotLength = oldKey.Length - areaPrefix.Length - areaSuffix.Length;
                    if (slotLength <= 0 || !int.TryParse(oldKey.AsSpan(areaPrefix.Length, slotLength),
                        System.Globalization.NumberStyles.None, System.Globalization.CultureInfo.InvariantCulture, out int physicalSlot) ||
                        physicalSlot is < 0 or > 500)
                        throw new InvalidDataException($"Unknown legacy area counter: {oldKey}.");
                    semanticKey = $"{areaPrefix}{physicalSlot}:owned-count-version";
                }
                else
                {
                    if (!oldKey.StartsWith("sc-rva:", StringComparison.Ordinal) &&
                        !oldKey.StartsWith("ce-city-capture-food-quote:parameter:", StringComparison.Ordinal)) continue;
                    if (!Keys.TryGetValue(oldKey, out semanticKey))
                        throw new InvalidDataException($"Unknown legacy simulation parameter: {oldKey}.");
                }
                JsonNode? value = bank[oldKey];
                if (bank.TryGetPropertyValue(semanticKey, out JsonNode? current))
                {
                    if (!JsonNode.DeepEquals(value, current))
                        throw new InvalidDataException($"Conflicting legacy simulation parameter: {semanticKey}.");
                    bank.Remove(oldKey);
                }
                else
                {
                    bank.Remove(oldKey);
                    bank[semanticKey] = value;
                }
            }
        }
    }

