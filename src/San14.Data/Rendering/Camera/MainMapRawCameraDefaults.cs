    internal static void ApplyFresh(Span<byte> storage)
    {
        foreach(var range in InitializedRanges)storage.Slice(range.Offset,range.ByteCount).Clear();
        foreach(var field in FloatDefaults)
            BinaryPrimitives.WriteSingleLittleEndian(storage.Slice(field.Offset,4),field.Value);
        foreach(var field in IntegerDefaults)
            BinaryPrimitives.WriteUInt32LittleEndian(storage.Slice(field.Offset,4),field.Value);
        WriteType(storage,0,RawCameraTypeTag.CameraAllocation);
        WriteType(storage,0x1330,RawCameraTypeTag.Perspective);
        WriteType(storage,0x2BF0,RawCameraTypeTag.ResourcePair);WriteType(storage,0x2C28,RawCameraTypeTag.ResourcePair);
        WriteType(storage,0x2C60,RawCameraTypeTag.ResourceSlot);WriteType(storage,0x2C78,RawCameraTypeTag.ResourceSlot);
        WriteType(storage,0x2C90,RawCameraTypeTag.ResourceSlot);
        storage[0x1491]=1; // Perspective mode initialized; projection update marked dirty.
    }
    private static void WriteType(Span<byte> storage,int offset,RawCameraTypeTag tag)
        =>BinaryPrimitives.WriteUInt64LittleEndian(storage.Slice(offset,8),(ulong)tag);

