    internal string ResolveProposalReport(INarrationCurrentContext context, Func<int, int> draw, int root)
    {
        if (!ProposalReportRoots.Contains(root)) throw Failure("proposal_report_root");
        _prefix = "proposal.text";
        bool previous = _report; _report = true;
        try
        {
            return ExecuteMessage(context, draw, root, Get(root), _ => false, true, null,
                ProposalReportMessages.Contains, escapeText: (group, code) => (group, code) switch
                { ('C', 'J') => "^02", ('C', 'L') => "^05", ('E', 'K') or ('E', 'M') => string.Empty,
                  _ => throw Failure($"unresolved_escape_{group:X2}_{code:X2}") }, allowOpaqueEscapes: true).Text;
        }
        finally { _report = previous; }
    }
