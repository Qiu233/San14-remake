    internal string ResolveStrategicCommandReport(INarrationCurrentContext context, Func<int, int> draw, int root)
    {
        if (!StrategicCommandRoots.Contains(root)) throw Failure("strategic_command_root");
        _prefix = "strategic.command.text";
        bool previous = _report; _report = true;
        try
        {
            return ExecuteMessage(context, draw, root, Get(root, true), _ => false, true, null,
                StrategicCommandMessages.Contains, (group, code) => (group, code) switch
                {
                    ('C', 'J') => "^02", ('C', 'L') => "^05",
                    ('E', 'K') or ('E', 'M') => string.Empty,
                    _ => throw Failure($"unresolved_escape_{group:X2}_{code:X2}")
                }, true).Text;
        }
        finally { _report = previous; }
    }
